def compute_image_ahash(image_bytes: bytes) -> str:
    """Computes an exact 64-bit (16 hex char) Average Perceptual Hash identical to the JS canvas."""
    img = Image.open(io.BytesIO(image_bytes)).convert('RGB').resize((8, 8), Image.Resampling.BILINEAR)
    pixels = list(img.getdata())
    grays = [(r + g + b) / 3.0 for r, g, b in pixels]
    mean = sum(grays) / len(grays)
    bits = ''.join('1' if val >= mean else '0' for val in grays)
    return ''.join(f"{int(bits[i:i + 4], 2):x}" for i in range(0, 64, 4))


def hamming_distance(h1: str, h2: str) -> int:
    """Calculates bit-level Hamming distance between two 16-character hex hashes (0 to 64)."""
    if not h1 or not h2 or len(h1) != 16 or len(h2) != 16:
        return 64
    b1 = bin(int(h1, 16))[2:].zfill(64)
    b2 = bin(int(h2, 16))[2:].zfill(64)
    return sum(c1 != c2 for c1, c2 in zip(b1, b2))


