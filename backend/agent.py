def scour_and_enforce(target_urls: list, threshold: int = 12) -> dict:
    """Scours target URLs, hashes all images, finds nearest Hamming distance, and enforces takedowns."""
    # 1. Load registered singular hashes from CSV
    registered_assets = []
    if os.path.exists(HASH_DB):
        with open(HASH_DB, 'r') as f:
            reader = csv.DictReader(f)
            registered_assets = list(reader)

    if not registered_assets:
        return {"status": "ERROR", "message": "No protected hashes in vault yet. Register an image first."}

    best_match = None

    # 2. Scour each target URL
    for page_url in target_urls:
        try:
            resp = requests.get(page_url, timeout=5)
            soup = BeautifulSoup(resp.text, 'html.parser')
            img_tags = soup.find_all('img')

            for img in img_tags:
                src = img.get('src')
                if not src:
                    continue
                img_url = urllib.parse.urljoin(page_url, src)
                img_resp = requests.get(img_url, timeout=5)
                if img_resp.status_code != 200:
                    continue

                detected_hash = compute_image_ahash(img_resp.content)

                # Compare against every protected hash using Hamming Distance
                for asset in registered_assets:
                    vault_hash = asset['image_hash']
                    dist = hamming_distance(vault_hash, detected_hash)
                    similarity = round(((64 - dist) / 64) * 100, 1)

                    if best_match is None or dist < best_match['distance']:
                        best_match = {
                            "vault_id": asset['id'],
                            "vault_hash": vault_hash,
                            "detected_hash": detected_hash,
                            "distance": dist,
                            "similarity": similarity,
                            "page_url": page_url,
                            "image_url": img_url
                        }
        except Exception as e:
            print(f"[Crawler] Error scanning {page_url}: {e}")

    if not best_match:
        return {"status": "CLEAN", "message": "Scoured targets. No reachable images found."}

    # 3. Check if nearest Hamming distance is within leak threshold (<= 12 bits out of 64)
    if best_match["distance"] <= threshold:
        whois_info = lookup_whois_host(best_match["page_url"])
        dmca_notice = generate_ai_dmca_notice(best_match, whois_info)
        email_sent = send_live_email(dmca_notice, whois_info["registrar"])

        # Execute active takedown if hosted on our simulated forum
        takedown_executed = False
        try:
            td_url = urllib.parse.urljoin(best_match["page_url"], '/takedown')
            td_res = requests.post(td_url, timeout=3)
            takedown_executed = (td_res.status_code == 200)
        except Exception:
            pass

        return {
            "status": "THREAT_MITIGATED",
            "match": best_match,
            "whois": whois_info,
            "email_sent": email_sent,
            "takedown_executed": takedown_executed,
            "dmca_preview": dmca_notice
        }

    return {
        "status": "CLEAN",
        "message": f"Closest image had Hamming distance {best_match['distance']}/64 (Threshold: {threshold}). No leak detected.",
        "closest_match": best_match
    }